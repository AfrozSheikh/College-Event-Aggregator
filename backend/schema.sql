-- ============================================================================
-- EVENTS
-- ============================================================================
CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    category VARCHAR(20) NOT NULL CHECK (category IN ('technical', 'cultural', 'sports', 'workshop', 'seminar', 'competition', 'conference')),
    location VARCHAR(200) NOT NULL,
    event_date DATE NOT NULL,
    event_time TIME NOT NULL,
    organized_by VARCHAR(200),
    organizer_department VARCHAR(100),
    rules_eligibility TEXT,
    max_participants INTEGER,
    registration_fees NUMERIC(10, 2) DEFAULT 0,
    created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_events_event_date ON events (event_date);
CREATE INDEX IF NOT EXISTS idx_events_created_by ON events (created_by);
CREATE INDEX IF NOT EXISTS idx_events_category ON events (category);
DROP TRIGGER IF EXISTS trg_events_updated_at ON events;
CREATE TRIGGER trg_events_updated_at BEFORE UPDATE ON events
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================================
-- EVENT PAYMENT QR (one QR image per event)
-- ============================================================================
CREATE TABLE IF NOT EXISTS event_payment_qr (
    event_id INTEGER PRIMARY KEY REFERENCES events(id) ON DELETE CASCADE,
    file_name VARCHAR(255),
    mime_type VARCHAR(100) NOT NULL,
    file_data BYTEA NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- EVENT GALLERY (event images)
-- ============================================================================
CREATE TABLE IF NOT EXISTS event_gallery (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    file_name VARCHAR(255),
    mime_type VARCHAR(100) NOT NULL,
    file_data BYTEA NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_event_gallery_event_id ON event_gallery (event_id);

-- ============================================================================
-- EVENT REPORTS (generated PDF reports)
-- ============================================================================
CREATE TABLE IF NOT EXISTS event_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL DEFAULT 'application/pdf',
    file_data BYTEA NOT NULL,
    generated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_event_reports_event_id ON event_reports (event_id);

-- ============================================================================
-- PARTICIPATIONS
-- ============================================================================
CREATE TABLE IF NOT EXISTS participations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone VARCHAR(15),
    college VARCHAR(150),
    course_year VARCHAR(100),
    team_members TEXT,
    registered_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_participations_event_student ON participations (event_id, student_id);
CREATE INDEX IF NOT EXISTS idx_participations_registered_at ON participations (registered_at);

-- ============================================================================
-- PARTICIPATION FILES (payment screenshots / documents)
-- ============================================================================
CREATE TABLE IF NOT EXISTS participation_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id INTEGER NOT NULL REFERENCES participations(id) ON DELETE CASCADE,
    file_type VARCHAR(20) NOT NULL CHECK (file_type IN ('document', 'payment_screenshot')),
    file_name VARCHAR(255),
    mime_type VARCHAR(100) NOT NULL,
    file_data BYTEA NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (participation_id, file_type)
);

-- ============================================================================
-- FEEDBACK (legacy rating form)
-- ============================================================================
CREATE TABLE IF NOT EXISTS feedback (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating INTEGER CHECK (rating >= 1 AND rating <= 5),
    comment TEXT,
    suggestions TEXT,
    submitted_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_feedback_event ON feedback (event_id);
CREATE INDEX IF NOT EXISTS idx_feedback_student ON feedback (student_id);

-- ============================================================================
-- DYNAMIC FEEDBACK FORMS
-- ============================================================================
CREATE TABLE IF NOT EXISTS feedback_forms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL DEFAULT 'Event Feedback Form',
    description TEXT,
    is_mandatory BOOLEAN DEFAULT TRUE,
    created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_feedback_forms_event ON feedback_forms (event_id);
CREATE INDEX IF NOT EXISTS idx_feedback_forms_created_by ON feedback_forms (created_by);
DROP TRIGGER IF EXISTS trg_feedback_forms_updated_at ON feedback_forms;
CREATE TRIGGER trg_feedback_forms_updated_at BEFORE UPDATE ON feedback_forms
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS feedback_questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id INTEGER NOT NULL REFERENCES feedback_forms(id) ON DELETE CASCADE,
    question_text TEXT NOT NULL,
    question_type VARCHAR(20) DEFAULT 'text' CHECK (question_type IN ('text', 'rating', 'textarea', 'multiple_choice')),
    options TEXT,
    is_required BOOLEAN DEFAULT TRUE,
    order_index INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_feedback_questions_form ON feedback_questions (form_id, order_index);

CREATE TABLE IF NOT EXISTS feedback_responses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id INTEGER NOT NULL REFERENCES feedback_forms(id) ON DELETE CASCADE,
    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    submitted_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (student_id, event_id)
);

CREATE TABLE IF NOT EXISTS feedback_answers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id INTEGER NOT NULL REFERENCES feedback_responses(id) ON DELETE CASCADE,
    question_id INTEGER NOT NULL REFERENCES feedback_questions(id) ON DELETE CASCADE,
    answer_text TEXT
);
CREATE INDEX IF NOT EXISTS idx_feedback_answers_response ON feedback_answers (response_id);

-- ============================================================================
-- NOTIFICATIONS
-- ============================================================================
CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(20) DEFAULT 'system' CHECK (type IN ('new_event', 'registration', 'feedback', 'system')),
    "read" BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications (user_id, "read");
CREATE INDEX IF NOT EXISTS idx_notifications_created ON notifications (created_at DESC);
