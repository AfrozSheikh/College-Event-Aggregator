-- ============================================================================
-- College Event Management System - PostgreSQL schema (Neon)
-- ============================================================================
-- Version: 4.0 (PostgreSQL)
-- All uploaded files (event images, payment QR codes, payment screenshots,
-- documents) and generated PDF reports are stored in the database as BYTEA.
--
-- Apply with:  npm run db:init   (runs scripts/init-db.js against Neon)
-- The script is safe to re-run: every statement uses IF NOT EXISTS.
-- ============================================================================

-- Dates like CURRENT_DATE should follow Indian time, not the server's UTC.
-- (Set at database level so it also applies through Neon's connection pooler.)
-- Run by init-db.js:  ALTER DATABASE <db> SET timezone TO 'Asia/Kolkata';

-- Keeps updated_at current on UPDATE (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP)
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- USERS
-- ============================================================================
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    phone VARCHAR(15),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('admin', 'faculty', 'student')),
    status VARCHAR(10) DEFAULT 'pending' CHECK (status IN ('approved', 'pending')),

    -- Role-specific fields
    faculty_id VARCHAR(50),
    department VARCHAR(100),
    college_name VARCHAR(150),
    course VARCHAR(100),
    year VARCHAR(10),

    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_users_role_status ON users (role, status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (LOWER(email));
DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

